
-- Tabel karyawan
CREATE TABLE IF NOT EXISTS karyawan (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nik VARCHAR(20) NOT NULL UNIQUE,
    nama VARCHAR(100) NOT NULL,
    jabatan VARCHAR(60) NOT NULL,
    gaji_pokok BIGINT NOT NULL,
    tunjangan BIGINT NOT NULL DEFAULT 0,
    aktif BOOLEAN NOT NULL DEFAULT TRUE
);


-- Tabel penggajian
CREATE TABLE IF NOT EXISTS penggajian (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    karyawan_id INTEGER NOT NULL,

    periode CHAR(7) NOT NULL,
    nik VARCHAR(20) NOT NULL,
    nama VARCHAR(100) NOT NULL,
    jabatan VARCHAR(60) NOT NULL,

    gaji_pokok BIGINT NOT NULL,
    tunjangan BIGINT NOT NULL DEFAULT 0,

    jam_lembur INTEGER NOT NULL DEFAULT 0,
    tarif_lembur BIGINT NOT NULL DEFAULT 0,
    uang_lembur BIGINT NOT NULL DEFAULT 0,

    potongan BIGINT NOT NULL DEFAULT 0,
    bruto BIGINT NOT NULL,
    netto BIGINT NOT NULL,

    dibuat_pada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_gaji_karyawan
        FOREIGN KEY (karyawan_id)
        REFERENCES karyawan(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_gaji_periode
        UNIQUE (karyawan_id, periode)
);
